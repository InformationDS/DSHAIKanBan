#!/usr/bin/env node
/**
 * Prepare the AIKanBan host-integration probe (task-3).
 *
 * Rebuilds everything the isolated probe host needs, from files that live in
 * this repository, so the probe is reproducible after `.probe-home/` is deleted
 * (for example by `tools/probe-host.mjs`, which wipes the home it is given):
 *
 *   1. `<home>/storages/workspace.json` — the durable workspace fixture. It
 *      reproduces the REAL project records observed in the live registry
 *      (`03696d17-…` / `D:\BaiduSyncdisk\dsh-plugin\AIKanBan` / `AIKanBan`, and
 *      `455306c1-…` / `D:\BaiduSyncdisk\dsh-plugin`), so the probe exercises the
 *      real project identity rather than an invented one. Session lists are
 *      empty because those sessions do not exist in the isolated home.
 *   2. `<home>/profiles/node_modules/@aikanban/probe/` — the probe plugin
 *      package, copied from `../` (see the note on copies below).
 *   3. `<home>/probe.patch.yml` — the one-shot `--patch` overlay, generated with
 *      absolute paths so the harness survives a workspace move.
 *
 * ## Why the probe plugin is copied, not linked
 *
 * Node resolves ESM specifiers from a module's **realpath**. A junction would
 * make the probe resolve its `@deepseek-ai/*` imports from this repository,
 * where no `node_modules` exists. A copy placed under
 * `<home>/profiles/node_modules/` resolves them from the isolated home's own
 * module tree, which the host populates at boot — the same shape a genuinely
 * installed plugin has.
 *
 * ## Why `--profile web` and not `headless`
 *
 * The Host session API (`sessionController`), the durable workspace registry and
 * the `turnOutline` projection are mounted by `@deepseek-ai/dsh-web-app`, which
 * the shipped `headless` profile does not include. Adding those rows by hand
 * drags in the client half (`fileUploads` → `connection` → the Web runtime), so
 * the faithful path is the real Web composition with `--port 0` (OS-assigned)
 * and `--no-open` (never launches a browser).
 *
 * @module packages/plugin/src/probe/harness/prepare
 */
import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
/** `packages/plugin/src/probe`. */
const PROBE_SOURCE = resolve(HERE, '..')
/** Repository root. */
export const WORKSPACE_ROOT = resolve(PROBE_SOURCE, '..', '..', '..', '..')
/** The real project this probe must exercise. */
export const PRIMARY_WORKSPACE_PATH = join(WORKSPACE_ROOT)
/** The second real workspace in the live registry (`dsh-plugin（旧）`). */
export const SECONDARY_WORKSPACE_PATH = resolve(WORKSPACE_ROOT, '..')
/** The probe plugin's package name, matching `../package.json`. */
export const PACKAGE_NAME = '@aikanban/probe'
/** Default isolated Harness home (gitignored; safe to delete). */
export const DEFAULT_HOME = join(WORKSPACE_ROOT, '.probe-home')

/** Files that make up the mountable probe package. */
const PACKAGE_FILES = ['package.json', 'index.js']

/** Real workspace records observed in the live registry, reproduced verbatim. */
const REAL_WORKSPACES = [
	{
		id: '03696d17-12c2-4d78-9b3e-ff3bdf9e6f10',
		path: PRIMARY_WORKSPACE_PATH,
		title: 'AIKanBan',
		createdAt: '2026-10-13T03:34:08.000Z'
	},
	{
		id: '455306c1-4d0a-42ad-ba21-d63b41d753d8',
		path: SECONDARY_WORKSPACE_PATH,
		title: 'dsh-plugin（旧）',
		createdAt: '2026-08-17T13:46:46.000Z'
	}
]

/**
 * Compose the durable workspace fixture written into the isolated home.
 *
 * @returns {string} pretty-printed JSON for `<home>/storages/workspace.json`.
 */
function workspaceFixture() {
	const workspaces = {}
	for (const row of REAL_WORKSPACES) {
		workspaces[row.id] = {
			path: row.path,
			title: row.title,
			sessionIds: [],
			createdAt: row.createdAt,
			updatedAt: row.createdAt
		}
	}
	return `${JSON.stringify({
		unit: { name: 'workspace', version: 2 },
		global: { initialized: true, workspaceIds: REAL_WORKSPACES.map((row) => row.id), archivedSessionIds: [] },
		tables: { workspaces }
	}, undefined, 2)}\n`
}

/**
 * Compose the `--patch` overlay that mounts the probe and nothing else.
 *
 * @param {string} home - isolated Harness home (holds the report).
 * @returns {string} YAML text.
 */
function overlay(home) {
	return `# GENERATED by packages/plugin/src/probe/harness/prepare.mjs — do not edit by hand.
#
# One-shot overlay for the isolated probe host. It exists only inside the
# gitignored probe home; no user profile is ever touched.
#
# Boot it with (launcher flags MUST precede the app's own flags, or \`--patch\`
# is passed through to the app and rejected):
#
#   DSH_HOME=${home}
#   node <dsh-cli>/lib/bin.js --profile web --patch ${join(home, 'probe.patch.yml')} --port 0 --no-open

- id: session-telemetry-otel
  disabled: true

- insert:
    - id: aikanban-probe
      name: '${PACKAGE_NAME}'
      config:
        reportPath: '${join(PROBE_SOURCE, 'evidence', 'probe-report.json')}'
        primaryWorkspacePath: '${PRIMARY_WORKSPACE_PATH}'
        secondaryWorkspacePath: '${SECONDARY_WORKSPACE_PATH}'
        missingWorkspacePath: '${join(home, 'does-not-exist')}'
        fixtureWorkspacePath: '${join(home, 'ws-fixture')}'
        probePrompt: >-
          Reply with the single word ACK, then use the pwsh tool to run the command
          \`Write-Output aikanban-probe-step-2\` and report its output. Do not do anything else.
        turnTimeoutMs: 240000
`
}

/**
 * Rebuild the isolated home's probe inputs.
 *
 * @param {string} [home] - isolated Harness home; defaults to `<workspace>/.probe-home`.
 * @returns {{ home: string, packageDir: string, patchPath: string, profileDir: string }} the prepared paths.
 */
export function prepare(home = DEFAULT_HOME) {
	const packageDir = join(home, 'profiles', 'node_modules', '@aikanban', 'probe')
	rmSync(packageDir, { recursive: true, force: true })
	mkdirSync(packageDir, { recursive: true })
	for (const file of PACKAGE_FILES) cpSync(join(PROBE_SOURCE, file), join(packageDir, file))

	mkdirSync(join(home, 'storages'), { recursive: true })
	writeFileSync(join(home, 'storages', 'workspace.json'), workspaceFixture())

	const patchPath = join(home, 'probe.patch.yml')
	writeFileSync(patchPath, overlay(home))
	mkdirSync(join(PROBE_SOURCE, 'evidence'), { recursive: true })

	return { home, packageDir, patchPath, profileDir: join(home, 'profiles', 'web') }
}

if (import.meta.main) {
	const home = process.argv[2] === undefined ? DEFAULT_HOME : resolve(process.argv[2])
	const prepared = prepare(home)
	process.stdout.write(`prepare: home       ${prepared.home}\n`)
	process.stdout.write(`prepare: plugin     ${prepared.packageDir}\n`)
	process.stdout.write(`prepare: overlay    ${prepared.patchPath}\n`)
	process.stdout.write(`prepare: report     ${join(PROBE_SOURCE, 'evidence', 'probe-report.json')}\n`)
}
